"""FCPXML 1.9 writer for the flight timeline.

Times are exact rationals, never floats. Asset durations sit on each clip's
native frame grid; spine offsets and durations, the sequence duration and
marker times sit on the sequence grid. The format ``name`` attribute is
omitted on purpose: it is optional, FilmCraft ignores it, and a wrong Final
Cut format name is worse than none. Clip markers on the primary storyline
import into FilmCraft as sequence markers (verified in its importer); Resolve
keeps them on the clip.
"""

from __future__ import annotations

import math
from collections import Counter
from collections.abc import Sequence
from dataclasses import dataclass, field
from fractions import Fraction
from pathlib import Path, PurePath
from xml.sax.saxutils import escape

from .clipprobe import ClipFacts
from .moments import Moment
from .provenance import generator_comment

FCPXML_VERSION = "1.9"
# Every file we write carries the generator comment; the CLI refuses to
# overwrite an .fcpxml without it (it may be the pilot's edited timeline).
GENERATOR_MARK = "Generated by DJI Metadata Embedder"

FormatKey = tuple[Fraction, int, int]


@dataclass(frozen=True)
class TimelineClip:
    facts: ClipFacts
    moments: list[Moment] = field(default_factory=list)


def fmt_time(t: Fraction) -> str:
    t = Fraction(t)
    if t == 0:
        return "0s"
    if t.denominator == 1:
        return f"{t.numerator}s"
    return f"{t.numerator}/{t.denominator}s"


def media_url(path: PurePath) -> str:
    """``file://`` URL; handles drive letters, UNC shares and UTF-8."""
    if not path.is_absolute():
        path = Path(path).resolve()
    return path.as_uri()


def _attr(value: object) -> str:
    return escape(str(value), {'"': "&quot;"})


def _key(f: ClipFacts) -> FormatKey:
    return (f.rate, f.width, f.height)


def _markers(
    moments: Sequence[Moment], start: Fraction, duration: Fraction, fd: Fraction
) -> list[str]:
    out = []
    for m in moments:
        s = round(Fraction(m.start_s) / fd) * fd
        if s >= duration:
            continue  # telemetry outlasting the video: no footage to mark
        e = math.ceil(Fraction(m.end_s) / fd) * fd
        s = min(max(s, Fraction(0)), duration - fd)
        e = min(max(e, s + fd), duration)
        out.append(
            f'              <marker start="{fmt_time(start + s)}" '
            f'duration="{fmt_time(e - s)}" value="{_attr(m.label)}" '
            f'note="{_attr(m.note)}"/>'
        )
    return out


def build_fcpxml(clips: Sequence[TimelineClip], name: str) -> str:
    if not clips:
        raise ValueError("a timeline needs at least one clip")
    keys = [_key(c.facts) for c in clips]
    counts = Counter(keys)
    top = max(counts.values())
    seq_key = next(k for k in keys if counts[k] == top)  # ties: first clip
    ids: dict[FormatKey, str] = {}
    resources: list[str] = []
    for key in [seq_key, *keys]:
        if key not in ids:
            ids[key] = f"r{len(ids) + 1}"
            rate, width, height = key
            resources.append(
                f'    <format id="{ids[key]}" frameDuration="{fmt_time(1 / rate)}" '
                f'width="{width}" height="{height}"/>'
            )
    seq_fd = 1 / seq_key[0]
    spine: list[str] = []
    offset = Fraction(0)
    for n, clip in enumerate(clips, start=1):
        f = clip.facts
        asset_id = f"a{n}"
        fid = ids[_key(f)]
        start = f.tc_start if f.tc_start is not None else Fraction(0)
        native = Fraction(f.frames) / f.rate
        resources.append(
            f'    <asset id="{asset_id}" name="{_attr(f.path.stem)}" '
            f'start="{fmt_time(start)}" duration="{fmt_time(native)}" '
            f'hasVideo="1" hasAudio="{int(f.has_audio)}" format="{fid}">'
        )
        resources.append(
            f'      <media-rep kind="original-media" src="{_attr(media_url(f.path))}"/>'
        )
        resources.append("    </asset>")
        duration = math.floor(native / seq_fd) * seq_fd
        if duration <= 0:
            continue  # shorter than one sequence frame
        fmt_attr = "" if _key(f) == seq_key else f' format="{fid}"'
        tag = (
            f'            <asset-clip ref="{asset_id}" offset="{fmt_time(offset)}" '
            f'name="{_attr(f.path.stem)}" start="{fmt_time(start)}" '
            f'duration="{fmt_time(duration)}"{fmt_attr} tcFormat="NDF"'
        )
        markers = _markers(clip.moments, start, duration, seq_fd)
        if markers:
            spine.append(tag + ">")
            spine.extend(markers)
            spine.append("            </asset-clip>")
        else:
            spine.append(tag + "/>")
        offset += duration
    lines = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        "<!DOCTYPE fcpxml>",
        generator_comment(),
        f'<fcpxml version="{FCPXML_VERSION}">',
        "  <resources>",
        *resources,
        "  </resources>",
        "  <library>",
        f'    <event name="{_attr(name)}">',
        f'      <project name="{_attr(name)}">',
        (
            f'        <sequence format="{ids[seq_key]}" duration="{fmt_time(offset)}" '
            'tcStart="0s" tcFormat="NDF">'
        ),
        "          <spine>",
        *spine,
        "          </spine>",
        "        </sequence>",
        "      </project>",
        "    </event>",
        "  </library>",
        "</fcpxml>",
        "",
    ]
    return "\n".join(lines)


def write_fcpxml(clips: Sequence[TimelineClip], name: str, out_path: Path) -> Path:
    out_path = Path(out_path)
    out_path.write_text(build_fcpxml(clips, name), encoding="utf-8", newline="\n")
    return out_path


def is_our_fcpxml(path: Path) -> bool:
    try:
        with open(path, encoding="utf-8", errors="replace") as fh:
            head = fh.read(1024)
    except OSError:
        return False
    return GENERATOR_MARK in head
